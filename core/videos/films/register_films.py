"""Copy each film's visuals/timing into public/films/<slug>/ and write src/kits/shots/films.ts + a composition list."""
import json, pathlib, shutil
C = pathlib.Path(__file__).resolve().parents[2]; F = C / "videos/films"; P = C / "public/films"
slugs = sorted(d.name for d in F.iterdir() if (d / "visuals.json").exists())
imp, ent = [], []
for i, s in enumerate(slugs):
    for f in ("visuals.json", "timing.json"): shutil.copy(F / s / f, P / s / f)
    imp += [f'import v{i} from "../../../public/films/{s}/visuals.json";', f'import t{i} from "../../../public/films/{s}/timing.json";']
    maps = []
    for m in sorted((P / s).glob("map_*.json")):
        k = m.stem[4:]; imp.append(f'import m{i}_{k} from "../../../public/films/{s}/{m.name}";'); maps.append(f"{k}: m{i}_{k} as unknown as MapData")
    ent.append(f'  {{ slug: "{s}", visuals: {{ ...(v{i} as unknown as Visuals), maps: {{ {", ".join(maps)} }} }} as Visuals, timing: t{i} as unknown as KitTiming }},')
src = ["// Generated by videos/films/register_films.py - the ten taught films (one ShotFilm composition each).",
       'import type { Visuals } from "./ShotFilm";', 'import type { MapData } from "../board/BoardFilm";', 'import type { KitTiming } from "../time";',
       *imp, "export const films: { slug: string; visuals: Visuals; timing: KitTiming }[] = [", *ent, "];", ""]
(C / "src/kits/shots/films.ts").write_text("\n".join(src)); print(slugs)
